function New-LifecycleScenario {
    param([Parameter(Mandatory)][string]$Name)
    $root = Join-Path $script:SuiteRoot $Name
    [void][IO.Directory]::CreateDirectory((Join-Path $root 'lifecycle'))
    $plan = New-DraftPlanObject -Root $root
    $planPath = Join-Path $root 'reviewed-plan.json'
    $bytes = (New-Object Text.UTF8Encoding($false)).GetBytes(($plan | ConvertTo-Json -Depth 5))
    [IO.File]::WriteAllBytes($planPath, $bytes)
    $scenario = [pscustomobject]@{
        Name = $Name
        Root = $root
        PlanPath = $planPath
        PlanHash = Get-Sha256Hex -Bytes $bytes
        ManifestPath = $plan.ManifestPath
        SettlementPath = $plan.SettlementPath
        GoalMarker = $plan.GoalMarker
        RecoveryLocalName = $plan.RecoveryLocalName
        RuntimeCredentialPath = $plan.RuntimeCredentialPath
        RecoveryCredentialPath = $plan.RecoveryCredentialPath
        RunCount = 0
    }
    $definition = [pscustomobject]@{
        ToolRoot = $script:ToolRoot
        PlanPath = $planPath
        PlanHash = $scenario.PlanHash
        DatabaseGuid = $fixtureDatabaseGuid
    }
    Write-FixtureText -Path (Join-Path $root 'scenario.json') -Text (ConvertTo-Json -InputObject $definition)
    return $scenario
}

function Read-LifecycleCalls {
    param([Parameter(Mandatory)]$Scenario, [Parameter(Mandatory)][string]$RunName)
    $path = Join-Path $Scenario.Root 'calls.jsonl'
    if (-not [IO.File]::Exists($path)) {
        return @()
    }
    $calls = @([IO.File]::ReadAllLines($path) | Where-Object { $_ } | ForEach-Object { $_ | ConvertFrom-Json })
    return @($calls | Where-Object Run -CEQ $RunName)
}

function Invoke-LifecycleRun {
    param(
        [Parameter(Mandatory)]$Scenario,
        [ValidateSet('New', 'Remove')][string]$Entry = 'New',
        [hashtable]$Arguments = @{},
        [hashtable]$Behavior = @{},
        [switch]$RealReader
    )
    $Scenario.RunCount++
    $name = 'run{0:D2}' -f $Scenario.RunCount
    $entryArguments = [ordered]@{
        ApprovalPlanPath = $Scenario.PlanPath
        ExpectedApprovalPlanHash = $Scenario.PlanHash
        Database = $database
        ManifestPath = $Scenario.ManifestPath
    }
    foreach ($key in $Arguments.Keys) {
        $entryArguments[$key] = $Arguments[$key]
    }
    $effective = [ordered]@{
        PreflightDatabaseCount = 0
        PreflightLoginCount = 0
        AccountOccupied = $false
        FailSql = ''
        FailMessage = ''
        FailInnerMessage = ''
        FailSqlNumber = 51199
        PendingAt = ''
        StubMigrations = $false
        SecretFilesVerified = $false
        SchemaRows = @()
        LocalUsers = @()
    }
    foreach ($key in $Behavior.Keys) {
        $effective[$key] = $Behavior[$key]
    }
    $request = [pscustomobject]@{
        Entry = $Entry
        RealReader = [bool]$RealReader
        Arguments = [pscustomobject]$entryArguments
        Behavior = [pscustomobject]$effective
    }
    $requestPath = Join-Path $Scenario.Root ($name + '.request.json')
    Write-FixtureText -Path $requestPath -Text (ConvertTo-Json -InputObject $request -Depth 6)
    $process = Invoke-PowerShellFile -File $harnessPath -Arguments @('-ScenarioRoot', $Scenario.Root, '-RunName', $name)
    $outcomePath = Join-Path $Scenario.Root ($name + '.outcome.json')
    $outcome = $null
    if ([IO.File]::Exists($outcomePath)) {
        $outcome = Read-FixtureText -Path $outcomePath | ConvertFrom-Json
    }
    $run = [pscustomobject]@{
        Scenario = $Scenario.Name
        Name = $name
        HarnessExit = $process.ExitCode
        HarnessError = $process.StdErr.Trim()
        Completed = $null -ne $outcome -and $process.ExitCode -eq 0
        Threw = $null -ne $outcome -and $outcome.Threw
        Message = $(if ($null -ne $outcome) { [string]$outcome.Message } else { '' })
        Calls = @(Read-LifecycleCalls -Scenario $Scenario -RunName $name)
    }
    $script:AllRuns.Add($run)
    return $run
}

function Get-CallNames {
    param([Parameter(Mandatory)]$Run)
