function Get-ManifestState {
    param([Parameter(Mandatory)]$Scenario)
    # Flow assertions also require the state their stimulus assumes, so an upstream failure cannot pass them.
    $current = Read-LifecycleManifest -Scenario $Scenario
    if ($null -eq $current) {
