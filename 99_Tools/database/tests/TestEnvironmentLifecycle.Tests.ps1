function global:Assert-HarnessContained {
    param([string]$Path)
    $full = [IO.Path]::GetFullPath($Path)
    if (-not $full.StartsWith($global:HarnessRoot + '\', [StringComparison]::OrdinalIgnoreCase)) {
        throw "Offline harness: path outside the scenario root: $full"
