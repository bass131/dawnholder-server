function global:Assert-HarnessContained {
    param([string]$Path)
    $full = [IO.Path]::GetFullPath($Path)
    if (-not $full.StartsWith($global:HarnessRoot + '\', [StringComparison]::OrdinalIgnoreCase)) {
        throw "Offline harness: path outside the scenario root: $full"
    }
}

function global:Get-HarnessJournal {
    # The on-disk manifest exactly as the product left it when a stubbed side effect was requested.
    $path = $global:HarnessContract.ManifestPath
    if (-not [IO.File]::Exists($path)) {
        return 'absent'
    }
    $manifest = [IO.File]::ReadAllText($path) | ConvertFrom-Json
    $steps = @($manifest.Steps | ForEach-Object { $_.Name + ':' + $_.Status })
    if ($null -ne $manifest.Cleanup) {
        $steps += @($manifest.Cleanup.Steps | ForEach-Object { 'Cleanup.' + $_.Name + ':' + $_.Status })
    }
    return 'State=' + $manifest.State + ';' + ($steps -join ',')
}

function global:Write-HarnessCall {
    param([string]$Name, [string]$Detail = '')
    $entry = [pscustomobject]@{
        Run = $global:HarnessRun
        Name = $Name
        Detail = $Detail
        Journal = Get-HarnessJournal
    }
    $line = (ConvertTo-Json -InputObject $entry -Compress) + "`n"
    [IO.File]::AppendAllText($global:HarnessCallsPath, $line)
}

function global:New-HarnessTable {
    param(
        [Parameter(Mandatory)][Collections.Specialized.OrderedDictionary]$Columns,
        [object[]]$Rows = @()
    )
    $table = [Data.DataTable]::new()
    foreach ($name in $Columns.Keys) {
        [void]$table.Columns.Add($name, $Columns[$name])
    }
    foreach ($row in $Rows) {
        $dataRow = $table.NewRow()
        foreach ($name in $Columns.Keys) {
            $dataRow[$name] = $row.$name
        }
        $table.Rows.Add($dataRow)
    }
    return , $table
}

