function Get-InstallerCoreMessage {
    param(
        [Parameter(Mandatory)][string]$ManifestPath,
        [string]$LockPath = '',
        [IO.FileAccess]$LockAccess = [IO.FileAccess]::ReadWrite,
        [string]$ConnectionDatabase = ''
    )
    # Opened as Lock-TestEnvironmentManifest opens it; the connection stays unopened like the harness one.
    # The optional values build the refusal counterexamples: another lock file, a read-only lock, another database.
    if (-not $LockPath) {
        $LockPath = $ManifestPath + '.lock'
    }
    if (-not $ConnectionDatabase) {
        $ConnectionDatabase = $database
    }
    $lock = [IO.File]::Open($LockPath, [IO.FileMode]::OpenOrCreate, $LockAccess, [IO.FileShare]::None)
    $connection = [Data.SqlClient.SqlConnection]::new(
        'Data Source=lpc:.\OFFLINESTUB;Initial Catalog=' + $ConnectionDatabase)
    try {
        return Get-ThrownMessage -Action {
            # Distinct block parameter names: dot-sourcing binds the installer's own parameters in this scope.
            & {
                param($ApprovedContract, $ApprovedDatabase, $CorePath, $CoreLock, $CoreConnection)
                . (Join-Path $script:ToolRoot 'Install-Database.ps1')
                Invoke-TestEnvironmentInstall -Contract $ApprovedContract -Database $ApprovedDatabase `
                    -ManifestPath $CorePath -Phase Baseline001 -Connection $CoreConnection -ManifestLock $CoreLock
            } $coreContract $database $ManifestPath $lock $connection
        }
    }
    finally {
        $lock.Dispose()
        $connection.Dispose()
    }
}
