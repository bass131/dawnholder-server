}

function Get-JournalAt {
    param([Parameter(Mandatory)]$Run, [Parameter(Mandatory)][string]$Name)
    $call = @($Run.Calls | Where-Object Name -CEQ $Name)
    if ($call.Count -eq 0) {
        return 'not reached'
    }
    return [string]$call[0].Journal
}

function Format-RunDetail {
    param([Parameter(Mandatory)]$Run)
