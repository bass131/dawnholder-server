function Get-PendingWriteText {
    param([Parameter(Mandatory)]$Scenario)
    $path = $Scenario.ManifestPath + '.pending'
    if (-not [IO.File]::Exists($path)) {
        return 'absent'
    }
    return Read-FixtureText -Path $path
}

function Get-JournalText {
    param([Parameter(Mandatory)]$Scenario)
    if (-not [IO.File]::Exists($Scenario.ManifestPath)) {
        return ''
    }
    return Read-FixtureText -Path $Scenario.ManifestPath
}

function Get-RunOutcomeText {
    param([Parameter(Mandatory)]$Scenario, [Parameter(Mandatory)]$Run)
    # Everything the entry point returned or threw as the harness captured it, plus the harness error stream.
    $path = Join-Path $Scenario.Root ($Run.Name + '.outcome.json')
    $text = $(if ([IO.File]::Exists($path)) { Read-FixtureText -Path $path } else { '' })
    return $Run.Message + $text + $Run.HarnessError
}

