function Get-FileHashHex {
    param([Parameter(Mandatory)][string]$Path)
    if (-not [IO.File]::Exists($Path)) {
        return 'absent'
    }
    return Get-Sha256Hex -Bytes ([IO.File]::ReadAllBytes($Path))
}

function Get-StepStatus {
