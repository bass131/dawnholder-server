function global:Invoke-HarnessMigrations {
    param($Connection, $Transaction = $null, [string]$Phase = 'Complete', $Contract = $null)
    $approved = $null -ne $Contract -and $Contract.ExecutionApproved -eq $true
    $detail = 'Approved=' + $approved + ';Database=' + $Connection.Database
    Write-HarnessCall -Name ('Migrations.' + $Phase) -Detail $detail
    if ($global:HarnessBehavior.MigrationSqlNumber) {
        # INSTALL-07 end to end: the runner's first command fails in the product Invoke-DbNonQuery that
        # Install-Database.ps1 dot-sourced. Only this lookup bypasses its blocking alias; the fake command throws an
        # in-memory SqlException with provider-like text, so no SqlCommand or engine is reached.
        . $global:HarnessSqlExceptionFactory
        $real = @(Get-Command -Name 'Invoke-DbNonQuery' -CommandType Function)
        $file = $(if ($real.Count -eq 1) {
                [IO.Path]::GetFullPath([string]$real[0].ScriptBlock.File)
            } else {
                'resolved=' + $real.Count
            })
        Write-HarnessCall -Name 'Migrations.ProductNonQuery' -Detail $file
        $expectedFile = [IO.Path]::GetFullPath((Join-Path $global:HarnessToolRoot 'Database.Common.ps1'))
        if (-not [string]::Equals($file, $expectedFile, [StringComparison]::OrdinalIgnoreCase)) {
            throw 'Offline harness could not resolve the product Invoke-DbNonQuery.'
        }
        $failure = New-TestSqlException -Number ([int]$global:HarnessBehavior.MigrationSqlNumber) `
            -Message 'Provider text near FAKE-SENTINEL-E2E-5T Password=fake-not-a-secret'
        $command = [pscustomobject]@{ CommandText = ''; CommandTimeout = 0; Transaction = $null; Failure = $failure }
        $command | Add-Member -MemberType ScriptMethod -Name ExecuteNonQuery -Value { throw $this.Failure }
        $command | Add-Member -MemberType ScriptMethod -Name Dispose -Value { }
        $fakeConnection = [pscustomobject]@{ Database = $Connection.Database; Command = $command }
        $fakeConnection | Add-Member -MemberType ScriptMethod -Name CreateCommand -Value { $this.Command }
        $null = & $real[0] -Connection $fakeConnection -Sql 'offline harness migration batch'
    }
    'Offline harness recorded the migration request.'
}

function global:Invoke-HarnessSql {
    param(
        $Connection,
        [string]$Sql,
        [hashtable]$Parameters = @{},
        $Transaction = $null,
        [string]$Result = 'Scalar'
    )
    $kind = Get-HarnessSqlKind -Sql $Sql
    Write-HarnessCall -Name ('Sql.' + $kind) -Detail $Connection.Database
    if ($kind -ceq 'Unexpected') {
        throw 'Offline harness: unexpected SQL reached the stub.'
    }
    $behavior = $global:HarnessBehavior
    if ($behavior.PendingAt -ceq $kind) {
        # Leaves what an interrupted journal write leaves behind, so the next product journal write must fail.
        $pendingPath = $global:HarnessContract.ManifestPath + '.pending'
        Assert-HarnessContained -Path $pendingPath
        if (-not [IO.File]::Exists($pendingPath)) {
            [IO.File]::WriteAllText($pendingPath, 'offline harness interrupted journal write')
        }
    }
    if ($behavior.FailSql -ceq $kind) {
        # By default the safe shape of the product wrapper: provider text suppressed, number kept in Data. A scenario
        # may instead inject unsuppressed provider-like text, an inner exception or a non-numeric code.
        $message = 'Offline harness injected SQL failure (provider number 51199).'
        if ($behavior.FailMessage) {
            $message = [string]$behavior.FailMessage
        }
        $inner = $null
        if ($behavior.FailInnerMessage) {
            $inner = [Exception]::new([string]$behavior.FailInnerMessage)
        }
        $failure = [InvalidOperationException]::new($message, $inner)
        $failure.Data['DatabaseSqlNumber'] = $behavior.FailSqlNumber
        throw $failure
    }
    switch ($kind) {
        'Preflight' {
            $columns = [ordered]@{
                DatabaseCount = [int]
                LoginCount = [int]
                ProductVersion = [string]
                ServerCollation = [string]
                OriginalLogin = [string]
            }
            $row = @{
                DatabaseCount = [int]$behavior.PreflightDatabaseCount
                LoginCount = [int]$behavior.PreflightLoginCount
                ProductVersion = '16.0.1000.6'
                ServerCollation = 'Latin1_General_CI_AS'
                OriginalLogin = 'FIXTUREHOST\executor'
            }
            $table = New-HarnessTable -Columns $columns -Rows @($row)
            return , $table
        }
        'DatabaseIdentity' {
            $columns = [ordered]@{
                DatabaseId = [int]
                CreationTime = [string]
                OwnerSid = [string]
                DatabaseGuid = [string]
                Collation = [string]
                Rcsi = [bool]
                State = [string]
            }
            $row = @{
                DatabaseId = 7
                CreationTime = '2026-10-04T08:30:00.123'
                OwnerSid = '0x010500000000000515000000010000000200000003000000E9030000'
                DatabaseGuid = $global:HarnessScenarioGuid
                Collation = 'Latin1_General_CI_AS'
                Rcsi = $false
                State = 'ONLINE'
            }
            $table = New-HarnessTable -Columns $columns -Rows @($row)
            return , $table
        }
        'ReadMarkers' {
            $columns = [ordered]@{
                name = [string]
                Value = [string]
            }
            $rows = @(
                @{ name = 'Dawnholder.DatabaseTool'; Value = 'development-v1' },
                @{ name = 'Dawnholder.D1bGoal'; Value = $global:HarnessContract.GoalMarker }
            )
            $table = New-HarnessTable -Columns $columns -Rows $rows
            return , $table
        }
        'ReadSchemaVersion' {
            $columns = [ordered]@{
                Version = [int]
                Name = [string]
                Checksum = [string]
            }
            $table = New-HarnessTable -Columns $columns -Rows @($behavior.SchemaRows)
            return , $table
        }
        'SessionId' {
            return 61
        }
        'LoginSid' {
            return $behavior.LoginSid
        }
        { $_ -in @('ActiveSessions', 'BindingMismatch', 'BindingCount', 'UserTriggers', 'LedgerCount') } {
            return 0
        }
        default {
            return -1
        }
    }
}

