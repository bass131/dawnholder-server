}

function Find-Calls {
    param([Parameter(Mandatory)]$Run, [Parameter(Mandatory)][string]$Pattern)
    return @($Run.Calls | Where-Object { $_.Name -cmatch $Pattern })
}

function Get-JournalAt {
    param([Parameter(Mandatory)]$Run, [Parameter(Mandatory)][string]$Name)
    $call = @($Run.Calls | Where-Object Name -CEQ $Name)
    if ($call.Count -eq 0) {
        return 'not reached'
    }
    return [string]$call[0].Journal
}

function Format-RunDetail {
    param([Parameter(Mandatory)]$Run)
    return ('{0}/{1} exit={2} threw={3} message=<{4}> calls={5} stderr=<{6}>' -f $Run.Scenario, $Run.Name,
        $Run.HarnessExit, $Run.Threw, $Run.Message, ((Get-CallNames -Run $Run) -join '>'), $Run.HarnessError)
}

