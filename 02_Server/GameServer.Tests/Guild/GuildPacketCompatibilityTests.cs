using System.Buffers.Binary;
using System.Net;
using Shared.GameData;
using Shared.Protocol;

namespace Dawnholder.Server.GameServer.Tests.Guild;

// Independent final review of G7 / I9 (goal 2026-10-14-guild-server, technical contract v1 「패킷 필드와 결과」):
// the frames the real server sends are compared byte for byte with frames written out by hand from the contract
// table, so neither GuildWire's reader nor the generated writer is the oracle. Literal sources: LittleEndian,
// [ushort size incl. header][ushort id], 44 = 66 + name bytes with the UInt16 name byte length at offset 64,
// 47 = 26; default guild 1 「새벽 길드」 (UTF-16LE C8 C0 · BD BC · 20 00 · 38 AE · DC B4); approved A values (seed 5,
// stronghold 30 at level 1, weapon 20 + Material(1) × 1 at level 0); the shared result codes. The communal
// revision has no contract value, so each frame takes the revision the same connection observed.
// Handshake v21 is also checked by InventoryProtocolContractTests; here v19 and v20 must stay outside
// the guild. Fixed generated bytes are owned by GuildProtocolContractTests.
[Collection("GameWorldRegistryTests")]
public sealed class GuildPacketCompatibilityTests : IDisposable
{
    const int GuildRevisionOffset = 17;
    const int ResultRequestedOffset = 6;
    const int ResultGuildRevisionOffset = 10;
    const int SnapshotSequenceOffset = 4;
    const int SnapshotChangeKindOffset = 12;

    static readonly IPEndPoint Endpoint = new(IPAddress.Loopback, 0);

    readonly GuildTestWorld _guild = new();

    public void Dispose() => _guild.Dispose();

    // The first member's admission 44 in Town: sequence 1, Membership, one seed (5), one member online, no personal
    // change yet, the approved prices, stronghold InsufficientCurrency (5 < 30) and the locked blacksmith.
    [Fact]
    public void FirstAdmission44_IsTheContractFrame_ByteForByte()
    {
        GuildClient first = _guild.JoinAndEnter(CharacterClass.Knight);

        byte[] admission = Assert.Single(first.Since(0, GuildWire.GuildSnapshotId));
        uint revision = BinaryPrimitives.ReadUInt32LittleEndian(admission.AsSpan(GuildRevisionOffset, 4));

        Assert.Equal(Snapshot(sequence: 1, changeKind: 1, revision), admission);
    }

    // D8 refusals answer 47 → 44 without a 36. A stale 45 echoes its own revision beside the current one; a payable
    // shape at 5 < 30 is InsufficientCurrency; a 46 before the blacksmith opens is FacilityLocked. Each 47 points at
    // the 44 that follows it, and the per-connection sequence goes 2, 3, 4 after the admission's 1.
    [Fact]
    public void RefusalsAtTheFirstSeed_AreTheContract47And44Frames_ByteForByte()
    {
        GuildClient member = _guild.JoinAndEnter(CharacterClass.Knight);
        byte[] admission = Assert.Single(member.Since(0, GuildWire.GuildSnapshotId));
        uint revision = BinaryPrimitives.ReadUInt32LittleEndian(admission.AsSpan(GuildRevisionOffset, 4));
        uint staleRevision = revision + 7;

        List<byte[]> stale = _guild.Act(member, GuildWire.StrongholdUpgrade(staleRevision));
        List<byte[]> poor = _guild.Act(member, GuildWire.StrongholdUpgrade(revision));
        List<byte[]> locked = _guild.Act(member, GuildWire.WeaponEnhance(0));

        byte[] staleResult =
        {
            0x1A, 0x00, 0x2F, 0x00,                         // size 26, id 47
            0x01, 0x01,                                     // StrongholdUpgrade, Stale
            0x00, 0x00, 0x00, 0x00,                         // requestedRevision (the stale one, copied in)
            0x00, 0x00, 0x00, 0x00,                         // guildRevision (current, copied in)
            0x00, 0x00, 0x00, 0x00,                         // inventoryRevision 0
            0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // snapshotSequence 2
        };
        byte[] poorResult =
        {
            0x1A, 0x00, 0x2F, 0x00,
            0x01, 0x07,                                     // StrongholdUpgrade, InsufficientCurrency
            0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00,
            0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // snapshotSequence 3
        };
        byte[] lockedResult =
        {
            0x1A, 0x00, 0x2F, 0x00,
            0x02, 0x05,                                     // WeaponEnhance, FacilityLocked
            0x00, 0x00, 0x00, 0x00,                         // requestedRevision 0 (the 46's personal revision)
            0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00,
            0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // snapshotSequence 4
        };
        Revisions(staleResult, requested: staleRevision, guild: revision);
        Revisions(poorResult, requested: revision, guild: revision);
        Revisions(lockedResult, requested: 0, guild: revision);

        Assert.Equal(new[] { staleResult, Snapshot(sequence: 2, changeKind: 0, revision) }, stale);
        Assert.Equal(new[] { poorResult, Snapshot(sequence: 3, changeKind: 0, revision) }, poor);
        Assert.Equal(new[] { lockedResult, Snapshot(sequence: 4, changeKind: 0, revision) }, locked);
    }

    // G7 with the current v21 admission contract: either old version is refused before guild membership.
    // The next v21 account is therefore the guild's only member and its first seed.
    [Theory]
    [InlineData(19)]
    [InlineData(20)]
    public void AnOldVersionConnection_NeverJoinsTheGuild_AndTheNextMemberIsTheFirstSeed(int clientVersion)
    {
        GuildClient old = new(_guild.World, "guild_old_client");
        old.OnConnected(Endpoint);
        old.OnRecvPacket(new C_Handshake { clientVersion = (ushort)clientVersion }.Write());
        old.OnRecvPacket(new C_Login { accountName = old.AccountName }.Write());
        _guild.World.Accounts.Tick();
        old.OnRecvPacket(GuildBoundaryFixture.SelectKnight());
        old.OnRecvPacket(GuildWire.GuildRequest());
        _guild.Settle();
        GuildClient member = _guild.JoinAndEnter(CharacterClass.Knight);

        S_HandshakeResult refused = new();
        refused.Read(new ArraySegment<byte>(Assert.Single(old.Since(0, (ushort)PacketID.S_HandshakeResult))));
        GuildSnapshot admission = GuildTestWorld.ReadSnapshot(
            Assert.Single(member.Since(0, GuildWire.GuildSnapshotId)));

        Assert.False(refused.ok);
        Assert.Equal(21, refused.serverVersion);
        Assert.True(old.IsClosing, "the refused connection is closed");
        Assert.False(old.IsLoggedIn, "a refused connection never logs in");
        Assert.True(old.EntityId < 0, "a refused connection never enters a map");
        Assert.Empty(old.Since(
            0, (ushort)PacketID.S_EnterMap, GuildWire.GuildSnapshotId, GuildWire.GuildActionResultId));
        Assert.Equal(ChangeKind.Membership, admission.ChangeKind);
        Assert.Equal(1, admission.MemberCount);
        Assert.Equal(1, admission.OnlineMemberCount);
        Assert.Equal(5, admission.Treasury);
    }

    // One member alone in Town at seed 5 with no personal change: everything except the sequence, the change kind
    // and the communal revision is fixed by the contract and approved A.
    static byte[] Snapshot(long sequence, byte changeKind, uint revision)
    {
        byte[] frame =
        {
            0x4C, 0x00, 0x2C, 0x00,                         // size 76 = 66 + 10, id 44
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // snapshotSequence (copied in)
            0x00,                                           // changeKind (copied in)
            0x01, 0x00, 0x00, 0x00,                         // guildId 1
            0x00, 0x00, 0x00, 0x00,                         // guildRevision (copied in)
            0x05, 0x00, 0x00, 0x00,                         // treasury 5: one seed
            0x01, 0x02, 0x00,                               // stronghold 1 of 2, blacksmith locked
            0x01, 0x00, 0x00, 0x00,                         // memberCount 1
            0x01, 0x00, 0x00, 0x00,                         // onlineMemberCount 1
            0x00, 0x00, 0x00, 0x00,                         // inventoryRevision 0: no personal change
            0x00, 0x01,                                     // weapon 0 of 1
            0x00, 0x00, 0x00, 0x00,                         // attackBonus 0
            0x1E, 0x00, 0x00, 0x00,                         // strongholdCost 30
            0x14, 0x00, 0x00, 0x00,                         // weaponCurrencyCost 20
            0x01, 0x00, 0x00, 0x00,                         // weaponMaterialId 1 (Material)
            0x01, 0x00, 0x00, 0x00,                         // weaponMaterialCount 1
            0x07,                                           // strongholdAvailability InsufficientCurrency
            0x05,                                           // weaponAvailability FacilityLocked
            0x0A, 0x00,                                     // name byte length 10 at offset 64
            0xC8, 0xC0, 0xBD, 0xBC, 0x20, 0x00, 0x38, 0xAE, 0xDC, 0xB4, // 새 벽 ' ' 길 드
        };
        BinaryPrimitives.WriteInt64LittleEndian(frame.AsSpan(SnapshotSequenceOffset, 8), sequence);
        frame[SnapshotChangeKindOffset] = changeKind;
        BinaryPrimitives.WriteUInt32LittleEndian(frame.AsSpan(GuildRevisionOffset, 4), revision);
        return frame;
    }

    static void Revisions(byte[] result, uint requested, uint guild)
    {
        BinaryPrimitives.WriteUInt32LittleEndian(result.AsSpan(ResultRequestedOffset, 4), requested);
        BinaryPrimitives.WriteUInt32LittleEndian(result.AsSpan(ResultGuildRevisionOffset, 4), guild);
    }
}
